for (const scenario of [
  { name: 'session remains valid just before 15 minutes', age_ms: 899_000, remaining_ms: 1000, expected: 200 },
  { name: 'session expires exactly 15 minutes after login', age_ms: 900_000, remaining_ms: 0, expected: 401 },
  { name: 'legacy seven-day session is capped at 15 minutes', age_ms: 3 * 86_400_000, remaining_ms: 4 * 86_400_000, expected: 401 },
  { name: 'an earlier stored session expiry is still enforced', age_ms: 60_000, remaining_ms: -1000, expected: 401 },
  { name: 'invalid session timestamps cannot authenticate', age_ms: NaN, remaining_ms: 60_000, expected: 401 },
]) {
  test(scenario.name, async (context) => {
    context.mock.method(Date, 'now', () => kSessionNow);
    const session_row = {
      id: 'staff-1', role: 'staff',
      session_created_at: Number.isFinite(scenario.age_ms)
        ? new Date(kSessionNow - scenario.age_ms).toISOString() : 'invalid',
      expires_at: new Date(kSessionNow + scenario.remaining_ms).toISOString(),
    };
    const deleted_sessions: unknown[][] = [];
    const database = {
      /**
       * Summary: Provide the narrow D1 statement interface used by session tests.
       * Parameters: sql is the non-null SQL statement generated by the Worker.
       * Return Value: A statement stub; unexpected operations fail assertions.
       * Side Effects & Constraints: Retains bound values in memory; never opens D1.
       */
      prepare(sql: string) {
        let parameters: unknown[] = [];
        return {
          /**
           * Summary: Capture the values bound to this test statement.
           * Parameters: values is the ordered parameter list, possibly empty.
           * Return Value: This statement stub for D1-compatible method chaining.
           * Side Effects & Constraints: Replaces only the captured in-memory list.
           */
          bind(...values: unknown[]) { parameters = values; return this; },
          /**
           * Summary: Return the scenario's authentication row.
           * Parameters: None; uses the enclosing SQL and session fixture.
           * Return Value: The session row; unexpected SQL rejects with an assertion.
           * Side Effects & Constraints: Read-only; retains the D1 method name.
           */
          async first() { assert.match(sql, /FROM session JOIN staff/); return session_row; },
          /**
           * Summary: Return an empty request history for an authenticated session.
           * Parameters: None; uses the enclosing SQL statement.
           * Return Value: Empty results; unexpected SQL rejects with an assertion.
           * Side Effects & Constraints: Read-only; retains the D1 method name.
           */
          async all() { assert.match(sql, /FROM leave_application/); return { results: [] }; },
          /**
           * Summary: Record the session invalidation attempted by the Worker.
           * Parameters: None; uses captured SQL and bound parameters.
           * Return Value: One changed row; unexpected SQL rejects with an assertion.
           * Side Effects & Constraints: Appends parameters to deleted_sessions only.
           */
          async run() { assert.match(sql, /DELETE FROM session/); deleted_sessions.push(parameters); return { meta: { changes: 1 } }; },
        };
      },
    };
    const response = await worker.request('http://127.0.0.1/api/applications', {
      headers: { Cookie: 'leaveflowse_session=test-session' },
    }, { DB: database as unknown as D1Database, ASSETS: {} as Fetcher });
    assert.equal(response.status, scenario.expected);
    if (scenario.expected === 401) {
      assert.deepEqual(deleted_sessions, [['test-session']]);
      assert.match(response.headers.get('set-cookie') ?? '', /Max-Age=0/i);
    } else {
      assert.deepEqual(await response.json(), { applications: [] });
      assert.deepEqual(deleted_sessions, []);
      assert.equal(response.headers.get('set-cookie'), null);
    }
  });
}

