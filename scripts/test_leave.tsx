test('annual and sick used quota plus remaining equal entitlement throughout reservation changes', () => {
  for (const leave_type of ['annual', 'sick'] as const) {
    const entitlement = leave_type === 'annual' ? 18 : 14;
    for (const quota of [
      { entitlement, pending: 0, spent: 0, remaining: entitlement, taken: 0 },
      { entitlement, pending: 3, spent: 0, remaining: entitlement - 3, taken: 0 },
      { entitlement, pending: 3, spent: 4, remaining: entitlement - 7, taken: 1 },
      { entitlement, pending: 0, spent: 7, remaining: entitlement - 7, taken: 1 },
      { entitlement, pending: 0, spent: 4, remaining: entitlement - 4, taken: 1 },
      { entitlement, pending: 4, spent: entitlement - 4, remaining: 0, taken: 2 },
      { entitlement, pending: 0, spent: 0, remaining: entitlement, taken: 0 },
    ]) {
      const profile = { ...kMe, quota: { ...kMe.quota, [leave_type]: quota } };
      const markup = renderToStaticMarkup(<StaticRouter><Home me={profile} /></StaticRouter>);
      const label = leave_type === 'annual' ? 'Annual leave' : 'Sick leave';
      const card = markup.match(/<section\b[^>]*>[\s\S]*?<\/section>/g)!.find((section) => section.includes(label))!;
      const displayed_used = Number(/Quota used this year \(pending and approved\)<\/dt><dd>(\d+) days<\/dd>/.exec(card)![1]);
      assert.equal(displayed_used, quota.pending + quota.spent);
      assert.equal(displayed_used + quota.remaining, entitlement);
    }
  }
});

