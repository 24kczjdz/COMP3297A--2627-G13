/**
 * Summary: Adapt an in-memory SQLite connection to the D1 read methods under test.
 * Parameters: database is an open, non-null connection owned by the caller.
 * Return Value: The narrow prepare/bind/all interface used by ReadLeaveSummary.
 * Side Effects & Constraints: Statements execute against real SQLite, not canned
 * results; this adapter neither opens a disk database nor closes the connection.
 */
function AdaptDatabase(database: DatabaseSync): D1Database {
  return {
    /**
     * Summary: Prepare the actual summary SQL for the in-memory database.
     * Parameters: sql is the trusted SQL generated by the Worker helper.
     * Return Value: A statement wrapper; invalid SQL throws immediately.
     * Side Effects & Constraints: Compiles SQL and retains local bound parameters.
     */
    prepare(sql: string) {
      const statement = database.prepare(sql);
      let parameters: (string | number | null)[] = [];
      return {
        /**
         * Summary: Bind the reporting identity, date, and entitlement values.
         * Parameters: values are ordered SQLite strings, numbers, or null values.
         * Return Value: This wrapper, matching the D1 chaining interface.
         * Side Effects & Constraints: Replaces only this statement's parameter list.
         */
        bind(...values: (string | number | null)[]) { parameters = values; return this; },
        /**
         * Summary: Execute the real SQLite query with the captured bindings.
         * Parameters: None; the generic row type describes the expected result.
         * Return Value: A D1-shaped results object; SQL errors reject the promise.
         * Side Effects & Constraints: Reads only the caller's in-memory database.
         */
        async all<Row>() {
          return { results: statement.all(...parameters) as Row[], success: true, meta: {} };
        },
      };
    },
  } as unknown as D1Database;
}

/**
 * Summary: Create historical fixture records and install the actual schema rules.
 * Parameters: records has valid ordered ISO ranges and supported types/statuses;
 * sql_now is a UTC ISO instant used by SQLite's now expressions. Neither is null.
 * Return Value: Two owned memory connections and their D1 read adapter.
 * Side Effects & Constraints: Reads migrations relative to the project working
 * directory. Callers close both connections. Setup failure closes them before
 * rethrowing; no existing database or migration file is changed.
 */
function CreateFixture(records: readonly FixtureRequest[], sql_now: string): SummaryFixture {
  const database = new DatabaseSync(':memory:');
  const clock_database = new DatabaseSync(':memory:');
  try {
    /**
     * Summary: Delegate native date arithmetic with a fixed SQLite current instant.
     * Parameters: operation is date or strftime; values are SQLite function inputs.
     * Return Value: The native SQLite text/null result; invalid arguments may throw.
     * Side Effects & Constraints: Queries the separate memory connection, preventing
     * recursive calls into these overrides; every non-now input is left unchanged.
     */
    function ReadClock(operation: 'date' | 'strftime', values: (string | number | null)[]) {
      const placeholders = values.map(() => '?').join(', ');
      const parameters = values.map((value) => value === 'now' ? sql_now : value);
      return clock_database.prepare(`SELECT ${operation}(${placeholders}) AS value`)
        .get(...parameters)!.value as string | null;
    }

    database.function('date', { varargs: true }, (...values) => ReadClock('date', values));
    database.function('strftime', { varargs: true }, (...values) => ReadClock('strftime', values));
    database.exec('PRAGMA foreign_keys = ON');
    database.exec(readFileSync(join(process.cwd(), 'migrations/0001_schema.sql'), 'utf8'));
    const insert_staff = database.prepare(`INSERT INTO staff
      (id, email, password_salt, password_hash, name, staff_code, birthday,
       department, year_joined, role, created_at)
      VALUES (?, ?, 'salt', 'hash', 'Summary fixture', ?, '1990-01-01',
              'Engineering', 2020, 'staff', '2020-01-01T00:00:00Z')`);
    insert_staff.run(kFixtureStaffId, 'summary@worksmartse.hk', 'SUMMARY-001');
    insert_staff.run('unrelated-staff', 'unrelated@worksmartse.hk', 'SUMMARY-002');
    const insert_request = database.prepare(`INSERT INTO leave_application
      (id, applicant_id, leave_type, start_date, end_date, reason, status,
       archived, submitted_at, decided_at, updated_at)
      VALUES (?, ?, ?, ?, ?, 'Historical fixture', ?, ?,
              '2020-01-01T00:00:00Z', '2020-01-01T01:00:00Z', '2020-01-01T01:00:00Z')`);
    for (const record of records) {
      insert_request.run(record.id, record.staff_id ?? kFixtureStaffId, record.leave_type,
        record.start_date, record.end_date, record.status,
        Number(record.status === 'Approved' || record.status === 'Disapproved'));
    }
    for (const filename of kSchemaMigrations) {
      database.exec(readFileSync(join(process.cwd(), 'migrations', filename), 'utf8'));
    }
    return { database, clock_database, binding: AdaptDatabase(database) };
  } catch (error) {
    database.close();
    clock_database.close();
    throw error;
  }
}

/**
 * Summary: Independently enumerate calendar days to predict an account's summary.
 * Parameters: records contains valid fixture ranges; today is the captured ISO
 * reporting date. Neither may be null; only kFixtureStaffId records are counted.
 * Return Value: Expected public quota fields for both leave types.
 * Side Effects & Constraints: Pure apart from local allocation; enumerates each
 * day rather than duplicating the SQL aggregate or julianday calculation.
 */
function ExpectedSummary(records: readonly FixtureRequest[], today: string): Me['quota'] {
  const expected: Me['quota'] = {
    annual: { entitlement: 18, spent: 0, pending: 0, taken: 0, remaining: 18 },
    sick: { entitlement: 14, spent: 0, pending: 0, taken: 0, remaining: 14 },
  };
  for (const record of records) {
    if ((record.staff_id ?? kFixtureStaffId) !== kFixtureStaffId) continue;
    const date = new Date(`${record.start_date}T00:00:00Z`);
    while (date.toISOString().slice(0, 10) <= record.end_date) {
      const current = date.toISOString().slice(0, 10);
      if (current.slice(0, 4) === today.slice(0, 4)) {
        const quota = expected[record.leave_type];
        if (record.status === 'Pending') quota.pending++;
        if (record.status === 'Approved') {
          quota.spent++;
          if (current <= today) quota.taken++;
        }
      }
      date.setUTCDate(date.getUTCDate() + 1);
    }
  }
  for (const quota of Object.values(expected)) {
    quota.remaining -= quota.pending + quota.spent;
  }
  return expected;
}

test('a captured reporting year retains both quotas when SQL crosses Hong Kong New Year', async () => {
  const fixture = CreateFixture([], '2026-12-31T16:00:00Z');
  try {
    assert.equal(fixture.database.prepare("SELECT date('now', '+8 hours') AS today").get()!.today, '2027-01-01');
    assert.equal(fixture.database.prepare('SELECT COUNT(*) AS count FROM leave_balance WHERE staff_id = ? AND calendar_year = 2026')
      .get(kFixtureStaffId)!.count, 0);
    const summary = await ReadLeaveSummary(fixture.binding, kFixtureStaffId, '2026-12-31');
    assert.deepEqual(summary, ExpectedSummary([], '2026-12-31'));
  } finally {
    fixture.database.close();
    fixture.clock_database.close();
  }
});

test('taken days use the captured date even when SQL has advanced past Hong Kong midnight', async () => {
  const records: FixtureRequest[] = [
    { id: 'ongoing', leave_type: 'sick', status: 'Approved', start_date: '2026-11-04', end_date: '2026-11-07' },
  ];
  const fixture = CreateFixture(records, '2026-11-05T16:00:00Z');
  try {
    assert.equal(fixture.database.prepare('SELECT taken_days FROM leave_balance WHERE staff_id = ? AND calendar_year = 2026 AND leave_type = ?')
      .get(kFixtureStaffId, 'sick')!.taken_days, 3);
    const summary = await ReadLeaveSummary(fixture.binding, kFixtureStaffId, '2026-11-05');
    assert.deepEqual(summary, ExpectedSummary(records, '2026-11-05'));
    assert.equal(summary.sick.taken, 2);
    assert.equal(summary.sick.spent, 4);
  } finally {
    fixture.database.close();
    fixture.clock_database.close();
  }
});

test('Oscar-shaped approved and pending future annual leave uses quota before leave starts', async () => {
  const records: FixtureRequest[] = [
    { id: 'approved', leave_type: 'annual', status: 'Approved', start_date: '2026-11-07', end_date: '2026-11-11' },
    { id: 'pending', leave_type: 'annual', status: 'Pending', start_date: '2026-11-12', end_date: '2026-11-16' },
    { id: 'cancelled', leave_type: 'annual', status: 'Cancelled', start_date: '2026-10-01', end_date: '2026-10-05' },
    { id: 'disapproved', leave_type: 'annual', status: 'Disapproved', start_date: '2026-10-06', end_date: '2026-10-10' },
    { id: 'another-account', staff_id: 'unrelated-staff', leave_type: 'annual', status: 'Approved', start_date: '2026-10-01', end_date: '2026-10-03' },
  ];
  const fixture = CreateFixture(records, '2026-11-05T04:00:00Z');
  try {
    const summary = await ReadLeaveSummary(fixture.binding, kFixtureStaffId, '2026-11-05');
    assert.deepEqual(summary, ExpectedSummary(records, '2026-11-05'));
    assert.equal(summary.annual.pending + summary.annual.spent, 10);
    assert.equal(summary.annual.remaining, 8);
    assert.equal(summary.annual.taken, 0);
  } finally {
    fixture.database.close();
    fixture.clock_database.close();
  }
});

test('cross-year reservations and taken days count only the reporting year segment', async () => {
  const records: FixtureRequest[] = [
    { id: 'year-crossing', leave_type: 'annual', status: 'Approved', start_date: '2026-12-30', end_date: '2027-01-03' },
    { id: 'year-crossing-pending', leave_type: 'sick', status: 'Pending', start_date: '2026-12-31', end_date: '2027-01-02' },
  ];
  const fixture = CreateFixture(records, '2027-01-02T04:00:00Z');
  try {
    for (const today of ['2026-12-29', '2026-12-31', '2027-01-01', '2027-01-03']) {
      const summary = await ReadLeaveSummary(fixture.binding, kFixtureStaffId, today);
      assert.deepEqual(summary, ExpectedSummary(records, today));
      for (const quota of Object.values(summary)) {
        assert.equal(quota.pending + quota.spent + quota.remaining, quota.entitlement);
      }
    }
  } finally {
    fixture.database.close();
    fixture.clock_database.close();
  }
});

test('both leave types match a daily oracle across leap dates, statuses, and reporting cutoffs', async () => {
  const records: FixtureRequest[] = [];
  for (const leave_type of ['annual', 'sick'] as const) {
    records.push(
      { id: `${leave_type}-approved`, leave_type, status: 'Approved', start_date: '2024-02-27', end_date: '2024-03-01' },
      { id: `${leave_type}-pending`, leave_type, status: 'Pending', start_date: '2024-03-05', end_date: '2024-03-07' },
      { id: `${leave_type}-cancelled`, leave_type, status: 'Cancelled', start_date: '2024-02-20', end_date: '2024-02-22' },
      { id: `${leave_type}-disapproved`, leave_type, status: 'Disapproved', start_date: '2024-02-23', end_date: '2024-02-25' },
    );
  }
  const fixture = CreateFixture(records, '2026-11-05T04:00:00Z');
  try {
    for (const today of ['2023-12-31', '2024-02-26', '2024-02-27', '2024-02-28', '2024-02-29', '2024-03-01', '2024-12-31', '2025-01-01']) {
      const summary = await ReadLeaveSummary(fixture.binding, kFixtureStaffId, today);
      assert.deepEqual(summary, ExpectedSummary(records, today));
      for (const quota of Object.values(summary)) {
        assert.equal(quota.pending + quota.spent + quota.remaining, quota.entitlement);
        assert.ok(quota.taken <= quota.spent);
      }
    }
  } finally {
    fixture.database.close();
    fixture.clock_database.close();
  }
});
